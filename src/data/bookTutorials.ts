const markers = ["①", "②", "③", "④", "⑤"];

export const BOOK_TUTORIAL_PROBLEMS: Problem[] = CATEGORIES.flatMap((category) =>
  category.subtypes.flatMap((subtype) =>
    subtype.kinds.map((kind) => {
      const item = CASES[kind.id];
      if (!item) throw new Error(`Missing tutorial case: ${kind.id}`);
      return {
        id: kind.tutorialId,
        type: "single-blank",
        internalTypeName: kind.name,
        typeLabel: `${category.name} / ${subtype.name}`,
        typeSummary: kind.description,
        strategy: kind.tip,
        stem: item.stem,
        passage: [{ id: "p1", text: item.passage, newParagraph: true }],
        choices: item.choices.map((text, index) => ({
          id: String(index + 1),
          marker: markers[index],
          text,
        })),
        answerId: String(item.answer + 1),
        steps: [
          { narration: `먼저 문제의 조건과 발문을 확인합니다. ${kind.tip}`, highlight: ["p1"] },
          { narration: item.clue, highlight: ["p1"] },
          {
            narration: `${item.reasoning} 따라서 정답은 ${markers[item.answer]}입니다.`,
            highlight: ["p1"],
            highlightChoices: [String(item.answer + 1)],
            reveal: true,
          },
        ],
      } satisfies Problem;
    }),
  ),
);

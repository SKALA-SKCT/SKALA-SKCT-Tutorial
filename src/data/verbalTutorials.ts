import type { Problem, ProblemType, Segment } from "../types";

const markers = ["①", "②", "③", "④", "⑤"];

interface VerbalProblemInput {
  id: string;
  type?: ProblemType;
  internalTypeName: string;
  strategy: string;
  stem: string;
  box?: string;
  passage: Array<string | Omit<Segment, "id">>;
  choices: string[];
  answer: number;
  evidence: number[];
  opening: string;
  analysis: string;
  decision: string;
}

function createVerbalProblem(input: VerbalProblemInput): Problem {
  const passage = input.passage.map((item, index) => ({
    id: `p${index + 1}`,
    ...(typeof item === "string" ? { text: item } : item),
  }));
  const evidenceIds = input.evidence.map((index) => `p${index + 1}`);
  const answerId = String(input.answer + 1);

  return {
    id: input.id,
    type: input.type ?? "single-blank",
    internalTypeName: input.internalTypeName,
    typeLabel: input.internalTypeName,
    typeSummary: input.internalTypeName,
    strategy: input.strategy,
    stem: input.stem,
    box: input.box,
    passage,
    choices: input.choices.map((text, index) => ({
      id: String(index + 1),
      marker: markers[index],
      text,
    })),
    answerId,
    steps: [
      {
        narration: input.opening,
        highlight: ["p1"],
        highlightBox: Boolean(input.box),
      },
      {
        narration: input.analysis,
        highlight: evidenceIds,
        highlightBox: Boolean(input.box),
      },
      {
        narration: input.decision,
        highlight: evidenceIds,
        highlightChoices: [answerId],
      },
      {
        narration: `근거와 가장 정확하게 일치하는 선지는 ${markers[input.answer]}입니다. 지문의 표현을 넓히거나 줄이지 않고 판단해야 합니다.`,
        highlight: evidenceIds,
        highlightChoices: [answerId],
        reveal: true,
      },
    ],
  };
}


const paragraphScrambles = [
  [2, 0, 4, 1, 3],
  [1, 3, 0, 4, 2],
  [4, 2, 1, 3, 0],
  [0, 3, 2, 4, 1],
  [3, 1, 4, 0, 2],
] as const;

export const PARAGRAPH_ORDER_QUESTIONS: ExampleQuestion[] = orderCases.map(
  ({ parts, explanation }, index) => {
    const markers = ["(가)", "(나)", "(다)", "(라)", "(마)"];
    const scramble = paragraphScrambles[index % paragraphScrambles.length];
    const labels = scramble.map(
      (partIndex, markerIndex) => `${markers[markerIndex]} ${parts[partIndex]}`,
    );
    const scrambleOrder: readonly number[] = scramble;
    const correctOrder = [0, 1, 2, 3, 4].map(
      (partIndex) => markers[scrambleOrder.indexOf(partIndex)],
    );
    const correct = correctOrder.join("-");
    const swap = (left: number, right: number) => {
      const order = [...correctOrder];
      [order[left], order[right]] = [order[right], order[left]];
      return order.join("-");
    };
    return defineQuestion(CATEGORY, "vc-paragraph-order-1", "문단 순서 배열", index, {
      stem: "다음 문단을 논리적 순서대로 바르게 배열한 것은?",
      passage: labels.join("\n\n"),
      ...rotateChoices(correct, [swap(0, 1), swap(1, 2), swap(2, 3), swap(3, 4)], index + 2),
      explanation: `${explanation} 따라서 올바른 순서는 ${correct}입니다.`,
    });
  },
);

export const VERBAL_STRUCTURE_QUESTIONS = [...INSERTION_QUESTIONS, ...PARAGRAPH_ORDER_QUESTIONS];

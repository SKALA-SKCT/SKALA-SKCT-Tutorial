function buildQuestions(
  kindId: string,
  kindName: string,
  stem: string,
  cases: JudgmentCase[],
): ExampleQuestion[] {
  return cases.map((item, index) =>
    defineQuestion(CATEGORY, kindId, kindName, index, {
      stem,
      passage: item.passage,
      ...rotateChoices(item.correct, item.wrongs, index),
      explanation: item.explanation,
    }),
  );
}


const markers = ["(가)", "(나)", "(다)", "(라)", "(마)"];

/** 제자리에 남는 문단이 두 개 이하인 배열만 쓴다. 조건을 만족하는 배열은 109가지다. */
const scrambles: number[][] = [];
const permute = (prefix: number[], rest: number[]) => {
  if (!rest.length) {
    if (prefix.filter((part, position) => part === position).length <= 2) scrambles.push(prefix);
    return;
  }
  rest.forEach((item, index) =>
    permute([...prefix, item], [...rest.slice(0, index), ...rest.slice(index + 1)]),
  );
};
permute([], [0, 1, 2, 3, 4]);

// 109는 소수라서 37씩 건너뛰면 60문항 모두 서로 다른 배열(서로 다른 정답 순서)을 받는다.
export const VC_PARAGRAPH_ORDER_EXTRA: ExampleQuestion[] = orderCases.map(
  ({ parts, explanation }, index) => {
    const scramble = scrambles[(index * 37 + 11) % scrambles.length];
    const markerOf = (partIndex: number) => markers[scramble.indexOf(partIndex)];
    const passage = scramble
      .map((partIndex, markerIndex) => `${markers[markerIndex]} ${parts[partIndex]}`)
      .join("\n\n");
    const correctOrder = [0, 1, 2, 3, 4].map(markerOf);
    const correct = correctOrder.join("-");
    const swap = (left: number) => {
      const order = [...correctOrder];
      [order[left], order[left + 1]] = [order[left + 1], order[left]];
      return order.join("-");
    };
    const pairs = [0, 1, 2, 3]
      .map((left) => correctOrder[left] + "와 " + correctOrder[left + 1])
      .join(", ");
    const body = explanation.replace(/\[(\d)\]/g, (_, digit: string) => markerOf(Number(digit)));
    return defineQuestion(CATEGORY, "vc-paragraph-order-1", "문단 순서 배열", 20 + index, {
      stem: "다음 문단을 논리적 순서대로 바르게 배열한 것은?",
      passage,
      ...rotateChoices(correct, [swap(0), swap(1), swap(2), swap(3)], index + 2),
      explanation: `${body} 나머지 선지는 각각 ${pairs}의 자리를 맞바꾼 배열이어서, 뒤 문단이 받아야 할 앞 문단의 내용이 제자리에 오지 않습니다. 따라서 올바른 순서는 ${correct}입니다.`,
    });
  },
);

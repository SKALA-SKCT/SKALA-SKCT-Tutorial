  question: string;
  /** always: 항상 참, never: 항상 거짓, possible: 가능한 것, pick: 특정 자리의 대상 */
  mode: "always" | "never" | "possible" | "pick";
  pick?: number;
  conditions: Line[];
  answer: Line | string;
  wrong: Array<Line | string>;
  hint: string;

function hasFinalConsonant(value: string) {
  const code = value.charCodeAt(value.length - 1);
  return code >= 0xac00 && code <= 0xd7a3 ? (code - 0xac00) % 28 !== 0 : false;
}

function topic(value: string) {
  return `${value}${hasFinalConsonant(value) ? "은" : "는"}`;
}

const MARKS = ["①", "②", "③", "④", "⑤"];
const MARK_TOPIC = ["①은", "②는", "③은", "④는", "⑤는"];
const COUNT_WORDS = ["한", "두", "세", "네", "다섯"];
const CASE_TOPIC = ["경우 1은", "경우 2는", "경우 3은", "경우 4는", "경우 5는"];

function* injections(size: number, slotCount: number, used: number[] = []): Generator<number[]> {
  if (used.length === size) {
    yield [...used];
    return;
  }
  for (let slot = 1; slot <= slotCount; slot += 1) {
    if (used.includes(slot)) continue;
    used.push(slot);
    yield* injections(size, slotCount, used);
    used.pop();
  }
}

function solve(puzzle: Puzzle) {
  const tagOrders = puzzle.tags
    ? [...injections(puzzle.tags.length, puzzle.tags.length)]
    : [[] as number[]];
  const survivors: State[] = [];
  for (const slots of injections(puzzle.names.length, puzzle.slots.length)) {
    for (const tagOrder of tagOrders) {
      const state: State = { pos: {}, tag: {} };
      puzzle.names.forEach((name, index) => {
        state.pos[name] = slots[index];
        if (puzzle.tags) state.tag[name] = puzzle.tags[tagOrder[index] - 1];
      });
      if (puzzle.conditions.every(([, rule]) => rule(state))) survivors.push(state);
    }
  }
  return survivors;
}

function describe(puzzle: Puzzle, state: State) {
  const byslot = puzzle.slots.map((label, index) => {
    const name = puzzle.names.find((item) => state.pos[item] === index + 1);
    const tag = name && puzzle.tags ? `(${state.tag[name]})` : "";
    if (puzzle.arrow) return `${name}${tag}`;
    return name ? `${label} ${name}${tag}` : `${label} 비어 있음`;
  });
  return byslot.join(puzzle.arrow ? " → " : ", ");
}

const toLine = (puzzle: Puzzle, item: Line | string): Line =>
  typeof item === "string" ? [item, at(item, puzzle.pick as number)] : item;

function build(puzzle: Puzzle, index: number): ExampleQuestion {
  const where = puzzle.intro.slice(0, 30);
  const survivors = solve(puzzle);
  if (survivors.length < 1 || survivors.length > 5)
    throw new Error(`조건추리 배치 수 ${survivors.length}개: ${where}`);
  const answerLine = toLine(puzzle, puzzle.answer);
  const wrongLines = puzzle.wrong.map((item) => toLine(puzzle, item));
  const truth = (rule: Rule) => survivors.map((state) => rule(state));
  const answerTruth = truth(answerLine[1]);
  const expectAnswer = {
    always: answerTruth.every(Boolean),
    pick: answerTruth.every(Boolean),
    never: answerTruth.every((value) => !value),
    possible: answerTruth.some(Boolean),
  }[puzzle.mode];
  if (!expectAnswer) throw new Error(`조건추리 정답이 성립하지 않음: ${where}`);
  for (const [text, rule] of wrongLines) {
    const values = truth(rule);
    const wrongOk = {
      always: values.some((value) => !value),
      pick: values.every((value) => !value),
      never: values.some(Boolean),
      possible: values.every((value) => !value),
    }[puzzle.mode];
    if (!wrongOk) throw new Error(`조건추리 오답이 정답 조건도 만족함: ${where} / ${text}`);
  }
  if (wrongLines.length !== 4) throw new Error(`조건추리 오답 수 오류: ${where}`);

  const rotated = rotateChoices(
    answerLine[0],
    wrongLines.map(([text]) => text),
    index,
  );
  const lineOf = (text: string) =>
    text === answerLine[0] ? answerLine : wrongLines.find(([item]) => item === text)!;

  const cases =
    survivors.length === 1
      ? `조건을 모두 만족하는 배치는 ${describe(puzzle, survivors[0])} 한 가지입니다.`
      : `조건을 모두 만족하는 배치는 ${COUNT_WORDS[survivors.length - 1]} 가지로, ${survivors
          .map((state, order) => `${CASE_TOPIC[order]} ${describe(puzzle, state)}`)
          .join(", ")}입니다.`;
  const caseList = (values: boolean[], wanted: boolean) => {
    const hits = values
      .map((value, order) => (value === wanted ? `경우 ${order + 1}` : ""))
      .filter(Boolean);
    return hits.length === values.length ? "어느 경우에나" : `${hits.join(", ")}에서`;
  };
  const others = rotated.choices
    .map((text, order) => ({ text, order }))
    .filter(({ order }) => order !== rotated.answer);
  let review: string;
  if (puzzle.mode === "pick") {
    const places = others.map(({ text }) => {
      const found = [...new Set(survivors.map((state) => state.pos[text]))].sort((a, b) => a - b);
      return `${topic(text)} ${found.map((slot) => puzzle.slots[slot - 1]).join(" 또는 ")}`;
    });
    review = `나머지 중 ${places.join(", ")}에 옵니다.`;
  } else if (puzzle.mode === "always") {
    review =
      survivors.length === 1
        ? `${others.map(({ order }) => MARKS[order]).join(", ")}${MARK_TOPIC[others.at(-1)!.order].slice(1)} 이 배치와 맞지 않습니다.`
        : `${others
            .map(
              ({ text, order }) =>
                `${MARK_TOPIC[order]} ${caseList(truth(lineOf(text)[1]), false).replace("어느 경우에나", "어느 경우에도")}`,
            )
            .join(", ")} 성립하지 않습니다.`;
  } else if (puzzle.mode === "never" && survivors.length === 1) {
    review = `${others.map(({ order }) => MARKS[order]).join(", ")}${MARK_TOPIC[others.at(-1)!.order].slice(1)} 이 배치에서 참입니다.`;
  } else if (puzzle.mode === "never") {
    review = `${others
      .map(({ text, order }) => `${MARK_TOPIC[order]} ${caseList(truth(lineOf(text)[1]), true)}`)
      .join(", ")} 참이 됩니다.`;
  } else {
    review = `${others.map(({ order }) => MARKS[order]).join(", ")}${MARK_TOPIC[others.at(-1)!.order].slice(1)} 어느 경우에도 성립하지 않습니다.`;
  }
  const answerNote =
    puzzle.mode === "possible" && survivors.length > 1
      ? ` ${MARK_TOPIC[rotated.answer]} ${caseList(answerTruth, true)} 성립합니다.`
      : "";

  return defineQuestion(CATEGORY, KIND_ID, "조건에 따른 순서 배치", 20 + index, {
    stem: `${puzzle.intro} 이에 대한 정보가 다음 <조건>과 같을 때, ${puzzle.question}`,
    passage: puzzle.conditions
      .map(([text], order) => `${"㉠㉡㉢㉣㉤㉥㉦"[order]} ${text}`)
      .join("\n"),
    passageLabel: "조건",
    ...rotated,
    explanation: `${puzzle.hint} ${cases} 따라서 정답은 ${MARKS[rotated.answer]}입니다.${answerNote} ${review}`,
  });
}

export const VR_CONDITION_EXTRA: ExampleQuestion[] = PUZZLES.map(build);

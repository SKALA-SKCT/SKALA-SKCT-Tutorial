const at =
  (a: string, k: number): Rule =>
  (s) =>
    s.pos[a] === k;
const notAt =
  (a: string, k: number): Rule =>
  (s) =>
    s.pos[a] !== k;
const before =
  (a: string, b: string): Rule =>
  (s) =>
    s.pos[a] < s.pos[b];
/** b가 a의 바로 다음 자리(번호가 1 큰 자리)에 온다. */
const next =
  (a: string, b: string): Rule =>
  (s) =>
    s.pos[b] === s.pos[a] + 1;
/** 두 대상의 자리 번호 차이가 d이다. 사이에 d - 1개의 자리가 있다. */
const apart =
  (a: string, b: string, d: number): Rule =>
  (s) =>
    Math.abs(s.pos[a] - s.pos[b]) === d;
const inSet =
  (a: string, ...ks: number[]): Rule =>
  (s) =>
    ks.includes(s.pos[a]);
const empty =
  (k: number): Rule =>
  (s) =>
    !Object.values(s.pos).includes(k);
const tagIs =
  (a: string, t: string): Rule =>
  (s) =>
    s.tag[a] === t;
const holder = (s: State, t: string) =>
  Object.keys(s.tag).find((name) => s.tag[name] === t) as string;
const tagAt =
  (t: string, k: number): Rule =>
  (s) =>
    s.pos[holder(s, t)] === k;
const not =
  (rule: Rule): Rule =>
  (s) =>
    !rule(s);
const and =
  (...rules: Rule[]): Rule =>
  (s) =>
    rules.every((rule) => rule(s));

